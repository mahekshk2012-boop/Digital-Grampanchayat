class LanguageManager {
  constructor() {
    this.currentLang = localStorage.getItem('gp_language') || 'en';
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindButtons();
  }

  setLanguage(lang) {
    if (lang !== 'en' && lang !== 'mr') return;
    this.currentLang = lang;
    localStorage.setItem('gp_language', lang);
    this.applyLanguage(lang);
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  get(key) {
    const dict = translations[this.currentLang] || translations.en;
    return dict[key] || translations.en[key] || key;
  }

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.get(key);
      if (text) {
        el.textContent = text;
      }
    });

    // Update all elements with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const placeholder = this.get(key);
      if (placeholder) {
        el.setAttribute('placeholder', placeholder);
      }
    });

    // Update active state in language selector pills/dropdowns
    document.querySelectorAll('.lang-btn').forEach(btn => {
      const targetLang = btn.getAttribute('data-lang');
      if (targetLang === lang) {
        btn.classList.add('bg-white', 'text-gov-navy', 'font-bold', 'shadow-sm');
        btn.classList.remove('text-white/80', 'hover:text-white');
      } else {
        btn.classList.remove('bg-white', 'text-gov-navy', 'font-bold', 'shadow-sm');
        btn.classList.add('text-white/80', 'hover:text-white');
      }
    });
  }

  bindButtons() {
    document.addEventListener('click', (e) => {
      const target = e.target.closest('[data-lang]');
      if (target) {
        const lang = target.getAttribute('data-lang');
        this.setLanguage(lang);
      }
    });
  }
}

